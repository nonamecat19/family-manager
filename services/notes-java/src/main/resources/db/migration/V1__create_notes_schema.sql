CREATE TABLE "groups"
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(255) NOT NULL,
    color      VARCHAR(32)  NOT NULL,
    version    BIGINT       NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL,
    updated_at TIMESTAMPTZ  NOT NULL
);

CREATE TABLE notes
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(255) NOT NULL,
    content    TEXT,
    status     VARCHAR(32)  NOT NULL,
    priority   VARCHAR(32)  NOT NULL,
    parent_id  BIGINT,
    group_id   BIGINT,
    version    BIGINT       NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL,
    updated_at TIMESTAMPTZ  NOT NULL,

    CONSTRAINT fk_notes_parent FOREIGN KEY (parent_id) REFERENCES notes (id) ON DELETE CASCADE,
    CONSTRAINT fk_notes_group FOREIGN KEY (group_id) REFERENCES "groups" (id) ON DELETE SET NULL
);

CREATE INDEX idx_notes_group_id ON notes (group_id);
CREATE INDEX idx_notes_parent_id ON notes (parent_id);
CREATE INDEX idx_notes_status ON notes (status);
