ALTER TABLE "groups" ADD COLUMN owner_user_id UUID;

CREATE INDEX idx_groups_owner ON "groups" (family_id, owner_user_id);
CREATE INDEX idx_notes_owner ON notes (family_id, owner_user_id, updated_at DESC);

CREATE TABLE shares
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id          UUID        NOT NULL,
    note_id            BIGINT,
    notebook_id        BIGINT,
    subject            SMALLINT    NOT NULL,
    member_user_id     UUID,
    permission         SMALLINT    NOT NULL,
    granted_by_user_id UUID        NOT NULL,
    version            BIGINT      NOT NULL,
    created_at         TIMESTAMPTZ NOT NULL,
    updated_at         TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_shares_note FOREIGN KEY (note_id) REFERENCES notes (id) ON DELETE CASCADE,
    CONSTRAINT fk_shares_notebook FOREIGN KEY (notebook_id) REFERENCES "groups" (id) ON DELETE CASCADE,
    CONSTRAINT ck_shares_one_target CHECK ((note_id IS NULL) <> (notebook_id IS NULL)),
    CONSTRAINT ck_shares_subject CHECK ((subject = 1 AND member_user_id IS NOT NULL)
        OR (subject = 2 AND member_user_id IS NULL)),
    CONSTRAINT ck_shares_permission CHECK (permission IN (1, 2))
);

CREATE INDEX idx_shares_note ON shares (note_id) WHERE note_id IS NOT NULL;
CREATE INDEX idx_shares_notebook ON shares (notebook_id) WHERE notebook_id IS NOT NULL;
CREATE INDEX idx_shares_member ON shares (family_id, member_user_id);

CREATE UNIQUE INDEX uq_shares_note_member ON shares (note_id, member_user_id)
    WHERE note_id IS NOT NULL AND subject = 1;
CREATE UNIQUE INDEX uq_shares_note_family ON shares (note_id)
    WHERE note_id IS NOT NULL AND subject = 2;
CREATE UNIQUE INDEX uq_shares_notebook_member ON shares (notebook_id, member_user_id)
    WHERE notebook_id IS NOT NULL AND subject = 1;
CREATE UNIQUE INDEX uq_shares_notebook_family ON shares (notebook_id)
    WHERE notebook_id IS NOT NULL AND subject = 2;

INSERT INTO shares (family_id, note_id, subject, permission, granted_by_user_id, version, created_at, updated_at)
SELECT family_id, id, 2, 2, owner_user_id, 0, NOW(), NOW()
FROM notes
WHERE owner_user_id IS NOT NULL;
