CREATE TABLE note_comments
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id      UUID        NOT NULL,
    note_id        BIGINT      NOT NULL,
    author_user_id UUID        NOT NULL,
    body           TEXT        NOT NULL,
    resolved       BOOLEAN     NOT NULL DEFAULT FALSE,
    version        BIGINT      NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_note_comments_note FOREIGN KEY (note_id) REFERENCES notes (id) ON DELETE CASCADE
);

CREATE INDEX idx_note_comments_note ON note_comments (note_id, family_id, created_at);

CREATE TABLE note_activity
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id     UUID        NOT NULL,
    note_id       BIGINT      NOT NULL,
    actor_user_id UUID        NOT NULL,
    kind          SMALLINT    NOT NULL,
    detail        TEXT        NOT NULL DEFAULT '',
    version       BIGINT      NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL,
    updated_at    TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_note_activity_note FOREIGN KEY (note_id) REFERENCES notes (id) ON DELETE CASCADE
);

CREATE INDEX idx_note_activity_note ON note_activity (note_id, family_id, created_at DESC);
